// Generates src/environments/version.ts before every build / serve so the back office can
// display the exact frontend version and build date.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const content = `// Generated by scripts/version.mjs — do not edit.
export const APP_VERSION = {
  version: '${pkg.version}',
  builtAt: '${new Date().toISOString()}',
} as const;
`;

mkdirSync(join(root, 'src/environments'), { recursive: true });
writeFileSync(join(root, 'src/environments/version.ts'), content);
console.log(`version.ts → ${pkg.version}`);

// The back office renders the repository changelog: ship it as a static asset.
const changelog = join(root, '..', 'CHANGELOG.md');
if (existsSync(changelog)) {
  copyFileSync(changelog, join(root, 'public', 'changelog.md'));
  console.log('changelog.md → public/');
}
